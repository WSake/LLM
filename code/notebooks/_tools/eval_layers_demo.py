def expA():
    print("=" * 72)
    print("[账 A] 三层定位——10 个典型问题，先归层再谈数字（扣口径的第一件事）")
    print("=" * 72)
    print("  五层定义（§11.0）：能力=模型本身多强 / 任务=你的业务任务 / 系统=RAG·Agent")
    print("  端到端 / 安全=威胁与护栏 / 工程=延迟·吞吐·成本。10 个问题摆归位：")
    print(f'    {"问题":<36}{"正确层":<6}代表尺子')
    correct = 0
    per_layer = {k[0]: 0 for k in LAYERS_A}
    for q, want, ruler, _ in QS_A:
        hit = want in per_layer
        correct += int(hit)
        if hit:
            per_layer[want] += 1
        print(f'    {q:<34}{want:<6}{ruler}')
    assert correct == len(QS_A), f"{correct}/{len(QS_A)}"
    assert all(per_layer[k] >= 1 for k in per_layer), per_layer
    assert all(per_layer[k] >= 2 for k in ("能力层", "任务层", "系统层")), per_layer
    print(f"\n  → 归类 {correct}/10 断言全过 · 五层全有代表 · 核心三层（能力/任务/系统）各 ≥2。")
    print("    读数一：同一个动作在不同层用不同的尺子，答案本就不该一样——MMLU 88 的模型")
    print("            接上你的业务评测集可能是 0.43，不是模型骗你，是你量的层换了。")
    print("    读数二：问题的『主尺度』指向答案的『主场馆』——选模型进能力层、调 prompt")
    print("            进任务层、改 RAG 进系统层、切部署进工程层、上护栏进安全层。")
    print("  → 断言：10/10 归类正确 · 五层全有代表 = 五根尺子各管一段，先归层再读数")

    # 每层配的已交付锚点也顺带展示（复习链，只引用不重测）
    print("    每层的『已交付锚点』（仓库里已经量过的尺子，只引用不重测）：")
