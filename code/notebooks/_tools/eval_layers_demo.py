def expC():
    print("=" * 72)
    print("[账 C] 三角色 × 五层矩阵——每种评测角色，主要量哪一层（§11.0）")
    print("=" * 72)
    lay = [k[0] for k in LAYERS_A]
    hdr = "".join(f"{k:^7}" for k in lay)
    print(f'    {"角色":<8} {hdr}')
    ok = 0
    focus_per_layer = {k: 0 for k in lay}
    for name, grades, note in ROLES_C:
        row = "".join(f"{grades[k]:^7}" for k in lay)
        print(f'    {name:<8} {row}  {note}')
    # 断言：三角色主层各与 §11.0 定义匹配，且五层全被某角色当"主"
    want_roles = {
        "选型评测": {"能力层"},
        "开发评测": {"任务层", "系统层"},
        "上线评测": {"系统层", "安全层", "工程层"},
    }
    for name, grades, _ in ROLES_C:
        mains = {k for k in lay if grades[k] == "主"}
        assert mains == want_roles[name], f"{name}: {mains}"
        for m in mains:
            focus_per_layer[m] += 1
        ok += 1
    assert ok == len(ROLES_C)
    assert all(focus_per_layer[k] >= 1 for k in lay), focus_per_layer
    print(f"  → 断言：三角色主层 3/3 确认 · 五层全被某角色当『主』= 没有哪一层不重要。")
    print("    选型主量能力（横向比能力）· 开发主量任务+系统（迭代对比）· 上线主量")
    print("    系统+安全+工程（线上效果与护栏）——三种角色管三类决策，别混着拍板。")
    print()
    print("  改动 → 最少要回跑哪把尺（口径落地的 5 条最小回归规则）：")
    ok2 = 0
    for chg, tgt, tool in RULES_C:
        ok2 += int(any(tgt.startswith(k.split("+")[0]) or k.split("+")[0] in tgt
                       for k in lay))
        print(f"    · {chg:<20} → {tgt:<12}（{tool}）")
    assert ok2 == len(RULES_C), f"{ok2}/{len(RULES_C)}"
    print(f"  → 断言：5/5『改动→尺子』配对。每次改完先想清楚动了哪一层，再选尺子回跑，")
    print("    层不用全跑——最小回归省时间，口径不丢不漏。")
    print()


