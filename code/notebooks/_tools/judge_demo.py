"""judge_demo.py —— §11.2 LLM-as-a-Judge 四账探针（11-评测与可观测 03 篇配套）

教偏置种类 + 判别性对照实验套路（与 notebook 010 同法）；里程碑 015 = LLM-as-Judge 长度偏置检测。

照例：**纯 stdlib · 零网络 · 零随机 · 零第三方**。stdout 三个独立进程逐字节 md5 恒一，
墙钟只进 stderr（W() 负责计时与落 stderr）。全部统计 = 本机确定性计算。

诚实边界（与文章头部 📌 一致）：
- 账 A 的 四个已知偏置（自夸/长度/位置/格式）与缓解手段 = 知识地图 §11.2 要素事实（非本机实测，
  写作环境无外网未在线复核）—— 偏置定义表/检测探针列 = 作者按 §11.2 预置的判定表；
- 账 B 的 "有偏置 judge" 与 "无偏置（内容对齐）judge" = **作者的两个确定性函数**（一个按长度判、
  一个按关键词覆盖判），配对样文 = 作者预置；偏置率/判别性计数 = 本机确定性计算；这就是"判别性对照"
  （010 同法）在本章的微型落地——**不是真实 LLM judge 在真实打分**；
- 账 C 的 三种判分带宽准确率/成本 = 作者预置仿真（词面规则 0.70/LLM judge 0.92/人工 0.97 与
  成本 $0/$0.0012/$1.50 展示"越贵越准"谱系，非某次真实评测）；judge v1→v2 判定翻转 6 条 = 作者预置
  算例（演示"judge 是模型，就会漂移"）；
- 账 D 的 上线装配六件套与人工子集校准（15 条不一致 3→1）= 作者预置仿真 + 本机确定性计算；
  **真实 LLM judge 部署 + 人工标注对齐 = 非本机实测**（need 模型 API 与标注，正文给推荐姿势）。

四账 = §11.2：四个已知偏置 × 检测探针（A）→ 长度偏置检测 + 缓解复测（B，里程碑 015）→
判分器演化谱系 + judge 漂移（C）→ judge 上线装配清单（D）。
"""
from __future__ import annotations
import sys
import time

_WSTART = time.perf_counter()


def W(msg: str) -> None:
    print(f"[wall] {time.perf_counter() - _WSTART:.3f}s  {msg}", file=sys.stderr)


# ---------------------------------------------------------------------------
# 账 A · 偏置种群账：§11.2 四个已知偏置 × 一句话 × 检测探针 × 缓解
# ---------------------------------------------------------------------------
BIASES = [
    ("自夸偏好", "judge 是模型，倾向点赞『看起来比自己强/同门』的输出",
     "同输出换两次模型名打分，分数是不是跟着名字动？", "匿名化（抹去模型名）+ rubric 只评内容"),
    ("长度偏置", "长答案判更高（字数=努力错觉）",
     "同一内容做成一短一长两版答案，谁分高？", "长度等化对照 + 评分 rubric 里去掉『详细=好』的暗示"),
    ("位置偏置", "排在前面的答案赢（首因效应）",
     "同一对答案 AB 与 BA 各判一次，结果一致吗？", "打乱顺序双跑 + 匿名化后固定同 prompt 模板"),
    ("格式偏置", "排版漂亮的分更高（Markdown/emoji/篇幅）",
     "同内容换两种排版打两次分，分数动没动？", "rubric 强制对内容不对格式 + 匿名化"),
]


def account_a() -> str:
    out = ["== A · 偏置种群账：四个已知偏置 × 检测探针 × 缓解 =="]
    for name, symptom, probe, remedy in BIASES:
        out.append(f"  · {name}：{symptom}")
        out.append(f"      检测探针：{probe}")
        out.append(f"      缓解：{remedy}")
    out.append(f"断言 4/4：四个已知偏置各配『检测探针 + 缓解』 = {'PASS' if len(BIASES) == 4 else 'FAIL'}"
               f"（会检测才谈缓解，判别性对照是公共套路）")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------------------
# 账 B · 长度偏置检测账（里程碑 015）：配对对照 + 判别性对照（010 同法）+ 缓解复测
# ---------------------------------------------------------------------------
# 10 对配对样文：内容同等质量（都是同一条事实的两种说法），仅长度不同。
# 布局（构造即确定）：pairs 0-6 长在 B；pair 7 长在 A；pair 8-9 等长（平局）。
PAIRS = [
    ("杠杆原理一句话：给一个支点，你可以撬动地球。",
     "杠杆原理说的是，只要找到一个合适的支点，再把力臂拉得足够长，一个人也能撬动很重的东西，所以有句老话说：给一个支点，你可以撬动地球。这句话传递的核心就是利用力臂放大优势。"),
    ("北京是中华人民共和国的首都。",
     "中华人民共和国的首都是北京，这也是一个大家都知道的常识，北京同时也是我国的政治中心、文化中心、国际交往中心和科技创新中心，很多国家级的机构都设在这里。"),
    ("水的化学式是 H2O。",
     "水的化学式是 H2O，也就是由两个氢原子和一个氧原子组成的化合物，常温下它是一种无色无味的透明液体，也是地球上最常见的物质之一，在生命活动中起着至关重要的作用。"),
    ("太阳从东方升起。",
     "太阳通常是从东方升起的，这是地球自转方向决定的，站在地球上的人每天的早晨都能看到太阳从地平线东边慢慢升起，到傍晚再从西边落下去，这一过程周而复始。"),
    ("一年有十二个月。",
     "一般来说，一年可以分为十二个月，其中有大月也有小月，比如一月三月五月七月八月十月十二月是大月，各有三十一天，其余各月有的三十天，二月比较特殊，平年二十九天。"),
    ("7 加 5 等于 12。",
     "在基本的加法运算中，7 加 5 的结果等于 12，这是最基础的算术题之一，日常生活中买东西找零钱也常常会用到类似的加法，熟练心算可以让人生活更方便。"),
    ("最大的陆地动物是非洲象。",
     "目前地球上最大的陆地动物是非洲象，成年雄性非洲象的肩高可以达到三到四米，体重有好几吨，它们长长的鼻子和宽大的耳朵是非常显著的特征，主要生活在非洲草原和森林地带。"),
    ("巴黎是法国的首都，以埃菲尔铁塔和塞纳河闻名，同时拥有大量博物馆与美术馆，是一座历史与艺术并存的大城市，人口超过两百万，地铁网络也非常发达，是欧洲重要的旅游目的地之一。",
     "巴黎是法国的首都。"),
    ("你好吗？我很好。",
     "小明你好，小华。"),
    ("请把灯关掉。",
     "请把门关上。"),
]


def account_b() -> str:
    out = []
    out.append("== B · 长度偏置检测账（里程碑 015）：检出 → 判别性对照 → 缓解复测 ==")

    # B1 配对对照：有偏置 judge（更长的赢）在 10 对上判出多少"长赢"
    long_scores = 0
    for a, b in PAIRS:
        la, lb = len(a), len(b)
        if la != lb:
            if la > lb:
                long_scores += 1  # 长=A（pair 7）
            else:
                long_scores += 1  # 长=B
        # 等长平局 → 判给第一位（A），不计入"长赢"
    bias_rate = long_scores / len(PAIRS)
    out.append(f"B1 配对对照（10 对同内容仅长度不同，有偏置 judge=更长的赢）：长赢 {long_scores}/{len(PAIRS)}"
               f" = 偏置率 {bias_rate:.2f} → {'检出长度偏置 PASS（>0.5 阈值）' if bias_rate > 0.5 else 'FAIL'}")
    lens = sorted({len(a) for a, _b in PAIRS} | {len(b) for _a, b in PAIRS})
    out.append(f"    样文长度池：{lens[0]}–{lens[-1]} 字符（A 长 1 对：{len(PAIRS[7][0])} vs {len(PAIRS[7][1])}"
               f"；等长 2 对：{len(PAIRS[8][0])}/{len(PAIRS[8][1])}、{len(PAIRS[9][0])}/{len(PAIRS[9][1])}）")

    # B2 判别性对照（010 同法）：好答案很短 vs 坏答案很长，看 judge 站哪边
    CONTR = [
        ("用户要一句『水的组成』，A 答：水由一个氧和两个氢组成。",
         "水的组成问题其实非常复杂，牵涉到化学、物理和生物等多个学科，需要从原子结构、分子构型、键能等多个角度综合分析，同时还要考虑温度压强等条件带来的变化，所以我先给出一个非常全面的概述……",
         ["氧", "氢"]),
        ("用户要『北京在哪里』，A 答：北京在中国，是中国的首都。",
         "关于北京这个问题，我们应该从地理、历史、政治、经济、文化等多个维度进行系统性讨论，其中地理因素尤为关键，城市的位置决定了它的气候、交通和战略地位，当然历史演变也不容忽视……",
         ["中国", "首都"]),
        ("用户要『太阳从哪升』，A 答：东方。",
         "太阳升起的方向问题在日常生活和科学认知中都非常重要，它是由地球自转轴的倾斜角度以及自转方向共同决定的，观察不同的季节和纬度，升起的方位还会发生明显变化，因此需要结合天文学知识……",
         ["东"]),
        ("用户要『7 加 5』，A 答：12。",
         "7 加 5 这道题看似简单，实际上它考察的是运算中的满十进位规则，即个位七加五等于十二，个位记二、向十位进一，所以最终结果是十二，这在竖式计算中非常常见……",
         ["12"]),
    ]

    def fair_score(text: str, kws) -> float:
        return sum(1 for k in kws if k in text) / len(kws)

    def bias_score(text: str) -> float:
        return 0.2 + 0.8 * min(len(text) / 160.0, 1.0)

    bad_won = 0
    good_won = 0
    for i, (good, bad, kws) in enumerate(CONTR, 1):
        if bias_score(bad) > bias_score(good):
            bad_won += 1
        if fair_score(good, kws) > fair_score(bad, kws):
            good_won += 1
        out.append(f"    组{i}：好答案 {len(good)} 字（覆盖 {len(kws)} 个关键点） vs 坏答案 {len(bad)} 字"
                   f" → 有偏置 judge 分数 {bias_score(good):.2f}/{bias_score(bad):.2f}（坏被吹高） · "
                   f"无偏置 judge 分数 {fair_score(good, kws):.2f}/{fair_score(bad, kws):.2f}（好该赢）")
    out.append(f"B2 判别性对照（010 同法：好指标必须能抓住坏答案）：有偏置 judge 判坏赢 {bad_won}/4（被长度骗）"
               f" · 无偏置 judge 判好赢 {good_won}/4（内容对齐） → "
               f"{'判别性 PASS：偏置 judge 会被『判别性对照』照出原形' if bad_won == 4 and good_won == 4 else 'FAIL'}")

    # B3 缓解复测：长度等化（把两版垫到同长度）后同 judge 再看 → 长度信号消失
    post = 0
    for a, b in PAIRS:
        if len(a) != len(b):
            long_side_is_a = len(a) > len(b)
            # 等化后平局 → 判给第一位 A；"长赢"只可能来自原本长在 A 的对
            if long_side_is_a:
                post += 1
    post_rate = post / len(PAIRS)
    out.append(f"B3 缓解复测（长度等化 + 匿名化 + 打乱顺序，残余 = 1 个位置偏置）：偏置率 "
               f"{bias_rate:.2f} → {post_rate:.2f} → {'缓解有效 PASS' if post_rate <= 0.1 else 'FAIL'}"
               f"（0.10 = 残余『排前面的赢』，总述：长度信号被掐掉，位置偏置浮出来）")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------------------
# 账 C · 判分器演化账（接 02 账 D 判分器演化史：词面规则 → LLM judge → 人工）
# ---------------------------------------------------------------------------
BANDS = [
    ("词面规则判分", 0.70, 0.0000, "02 账 D 快评台同款：零成本·确定性·漏语义（双刃）"),
    ("LLM judge", 0.92, 0.0012, "通用任意任务·可规模化·会漂移需校准"),
    ("人工评审", 0.97, 1.5000, "黄金标杆·最贵·量小一致性难，用于关键门禁与校准"),
]
# judge 版本漂移：同一批 20 样本，v1→v2 有 6 条判定翻转
DRIFT_FLIPS, DRIFT_N = 6, 20


def account_c() -> str:
    out = ["== C · 判分器演化账：越贵越准的谱系 + judge 会漂移 =="]
    for name, acc, cost, note in BANDS:
        out.append(f"  · 判分器带宽「{name}」：{acc:.2f} 准确率 / ${cost:.4f} 每条 / {note}")
    accs = [b[1] for b in BANDS]
    out.append(f"断言 谱系 PASS：准确率与成本同向（{accs[0]:.2f}→{accs[2]:.2f} 随 ${BANDS[0][2]:.4f}→"
               f"${BANDS[2][2]:.4f}）= 判分是『成本-准确率』权衡谱系，不是单一最优")
    out.append(f"judge 漂移账：同 20 样本，judge 版本 v1→v2 判定翻转 {DRIFT_FLIPS} 条 = 漂移率 "
               f"{DRIFT_FLIPS / DRIFT_N:.2f} → judge 是模型就会漂移，必须版本锁定（01 账 D 环境固定四件套③）")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------------------
# 账 D · judge 上线装配清单：六件套断言 6/6 + 人工子集校准小闭环
# ---------------------------------------------------------------------------
CHECKLIST = [
    ("固定版本 + 温度", "judge 换版本/换温度结论就变（C 账漂移 0.30），锁版本锁 temperature=0"),
    ("rubric 显式化", "判分标准写死在 rubric，不用默会；各档定义给出示例"),
    ("匿名化", "抹去模型名/品牌，防自夸偏好（A 账）"),
    ("打乱顺序 + 多 judge 投票", "AB 与 BA 都判（防位置偏置），3 个 judge 投票取多数（防单 judge 漂移）"),
    ("人工子集定期校准", "抽 N 条人工标注对齐 judge，不一致的逐条回写 rubric（§11.2 实践）"),
    ("偏置自查微型探针", "长度/位置/自夸三对对照题常驻，每次上线前跑一遍（B 账同款）"),
]


def account_d() -> str:
    out = []
    out.append("== D · judge 上线装配清单：六件套断言 6/6 ==")
    for i, (name, why) in enumerate(CHECKLIST, 1):
        out.append(f"  {i}. {name}——{why}")
    out.append(f"六件套断言 {len(CHECKLIST)}/{len(CHECKLIST)}：{'PASS' if len(CHECKLIST) == 6 else 'FAIL'}"
               f"（judge 不是『调个 prompt』，是装配起来的判分小系统）")
    # 人工子集校准小闭环
    n_sub, mismatch0, mismatch1 = 15, 3, 1
    out.append(f"人工子集校准小闭环：抽 {n_sub} 条人工标注对齐 judge → 初轮不一致 {mismatch0} 条（{mismatch0 / n_sub:.2f}）"
               f" → 逐条复盘回写 rubric → 复测不一致 {mismatch1} 条（{mismatch1 / n_sub:.2f}） → "
               f"{'校准闭环 PASS：不一致减半以上才允许上生产' if mismatch1 <= mismatch0 / 2 else 'FAIL'}")
    return "\n".join(out) + "\n"


def main() -> None:
    W("start")
    parts = [account_a(), account_b(), account_c(), account_d()]
    print("\n" + "\n".join(parts), end="")
    W("done")


if __name__ == "__main__":
    main()
