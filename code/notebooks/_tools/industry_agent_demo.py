print("\nC2 人机协同审批节奏 mock 6/6（Agent 提案 → 人工批准 4 / 打回 2 → 打回后修订再提 2/2 批准 → 终批准 6/6）：")
PROP = ["节奏-处方", "放款-初评", "发布-补丁", "签署-条款", "中台-脱敏", "生产-配置"]
APPROVE, REWORK = ["节奏-处方", "放款-初评", "签署-条款", "生产-配置"], ["发布-补丁", "中台-脱敏"]
cir = 0
for p in APPROVE:
    cir += 1                       # 提案 1 轮=直接批准
    print("       %s → 批准（1 轮）" % p)
for p in REWORK:
    cir += 2                       # 提案→打回→修订→批准 = 2 轮
    print("       %s → 打回 → 修订 → 批准（2 轮）" % p)
t(cir == len(APPROVE) + 2 * len(REWORK))
t(len(APPROVE) == 4 and len(REWORK) == 2 and len(APPROVE) + len(REWORK) == len(PROP))
rework_rate = len(REWORK) / len(PROP)
print("\nC3 打回率=2/6=%.1f%%（→修订成本：人工打回 1 次=Agent 多跑 1 轮再提；高危动作宁可打回不可放行）" % (100 * rework_rate))
t(abs(rework_rate - 2 / 6) < 1e-9 and rework_rate <= 0.34)

